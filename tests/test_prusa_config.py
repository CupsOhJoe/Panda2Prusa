def test_filament_base_falls_back_to_printer_default(fake_install):
    """A project preset left selected in PrusaSlicer is not an installed preset; the
    printer's default filament profile stands in, then the material match applies."""
    from panda2prusa.bambu_config import BambuConfig
    from panda2prusa.convert import resolve_target

    ini = os.path.join(fake_install.config_dir, "PrusaSlicer.ini")
    with open(ini, encoding="utf-8") as f:
        text = f.read()
    text = text.replace(
        "filament = Generic PLA @TEST\nfilament_1 = Generic PETG @TEST\n",
        "filament = proj.3mf (Bambu PLA Basic @BBL P2S)\nfilament_1 = proj.3mf (Generic PETG @BBL P2S)\n",
    ).replace("print = 0.20mm TEST\n", "print = proj.3mf (0.20mm Standard @BBL P2S)\n")
    with open(ini, "w", encoding="utf-8") as f:
        f.write(text)
    bambu = BambuConfig(
        {"filament_type": ["PLA", "PETG"], "filament_colour": ["#111111", "#222222"], "nozzle_diameter": ["0.4"]}
    )
    target = resolve_target("auto", bambu, {1: 1, 2: 2}, prusa_config_dir=fake_install.config_dir)
    assert target.filament_base_names[:2] == ["Generic PLA @TEST", "Generic PETG @TEST"]
    assert target.filament_bases[1].get("filament_type") == "PETG"
    assert target.print_base_name == "0.20mm TEST"
    assert target.print_base.get("fill_density") == "15%"


