def test_install_selection_and_version(fake_install):
    assert fake_install.version == "2.9.6"
    assert fake_install.selected("printer") == "Test Printer 5T 0.4 nozzle"
    assert fake_install.selected("print") == "0.20mm TEST"
    assert fake_install.selected_filaments() == ["Generic PLA @TEST", "Generic PETG @TEST"]
    assert fake_install.selected("sla_material") is None


def test_vendor_inheritance_chain(fake_install):
    cfg = fake_install.preset("printer", "Test Printer 5T 0.4 nozzle")
    assert cfg is not None
    # own value beats parents, grandparent values survive, meta keys are stripped
    assert cfg.vector("nozzle_diameter") == ["0.4"] * 5
    assert cfg.vector("retract_length") == ["0.7"] * 5
    assert cfg.get("bed_shape") == "0x0,250x0,250x210,0x210"
    assert cfg.get("gcode_flavor") == "marlin"
    assert cfg.get("extruder_colour") == "#FF8000;#DB5182;#3EC0FF;#FF4F4F;#FBEB7D"
    assert "inherits" not in cfg and "renamed_from" not in cfg
    assert fake_install.extruder_count(cfg) == 5


def test_multiple_parents_apply_in_order(fake_install):
    cfg = fake_install.preset("filament", "Generic PLA @TEST")
    assert cfg.get("filament_type") == "PLA"
    assert cfg.get("temperature") == "230"  # later parent overrides earlier one
    assert cfg.get("filament_multitool_ramming") == "1"
    assert cfg.get("filament_vendor") == "Generic"


