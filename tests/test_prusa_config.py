"""PrusaSlicer config serialization and preset resolution."""

import os
import textwrap

import pytest

from panda2prusa.prusa_config import (
    PrusaConfig,
    PrusaInstall,
    escape_string,
    escape_strings,
    parse_ini_sections,
    unescape_string,
    unescape_strings,
)


@pytest.mark.parametrize(
    "values, text",
    [
        (["PLA", "PLA"], "PLA;PLA"),
        (["Prusament PLA @XLIS", "Generic PLA"], '"Prusament PLA @XLIS";"Generic PLA"'),
        ([""], '""'),
        (["", ""], ";"),
        (["a;b", "c"], '"a;b";c'),
        (['say "hi"', "x\\y"], '"say \\"hi\\"";"x\\\\y"'),
        (["line1\nline2"], '"line1\\nline2"'),
    ],
)
def test_strings_escape_roundtrip(values, text):
    assert escape_strings(values) == text
    assert unescape_strings(text) == values


def test_string_escape_roundtrip():
    s = 'M862.3 P "XL" ; check\nG90\\n ; literal backslash-n\r\n'
    assert unescape_string(escape_string(s)) == s
    assert "\n" not in escape_string(s)


def test_slic3r_pe_text_roundtrip():
    text = textwrap.dedent(
        """\
        ; generated by PrusaSlicer 2.9.6 on 2026-07-12 at 05:13:37 UTC

        ; bed_shape = 0x0,360x0,360x360,0x360
        ; filament_settings_id = "Prusament PLA @XLIS";"Prusament PLA @XLIS"
        ; filament_notes = ;
        ; start_gcode = M17 ; enable steppers\\nG90
        ; layer_height = 0.2
        """
    )
    cfg = PrusaConfig.from_slic3r_pe_text(text)
    assert cfg.get("layer_height") == "0.2"
    assert cfg.get("start_gcode") == "M17 ; enable steppers\\nG90"
    assert cfg.vector("filament_settings_id") == ["Prusament PLA @XLIS", "Prusament PLA @XLIS"]
    assert cfg.vector("filament_notes") == ["", ""]
    assert cfg.vector("bed_shape") == ["0x0", "360x0", "360x360", "0x360"]
    out = cfg.to_slic3r_pe_text()
    again = PrusaConfig.from_slic3r_pe_text(out)
    assert dict(again.items()) == dict(cfg.items())


def test_vector_helpers_and_resize():
    cfg = PrusaConfig()
    cfg.set("temperature", ["220", "230"])
    assert cfg.get("temperature") == "220,230"
    cfg.set_vector("filament_type", ["PLA", "Generic PETG"])
    assert cfg.get("filament_type") == 'PLA;"Generic PETG"'
    cfg.resize_vectors(4, ["temperature", "filament_type", "layer_height"])
    assert cfg.vector("temperature") == ["220", "230", "230", "230"]
    assert cfg.vector("filament_type") == ["PLA", "Generic PETG", "Generic PETG", "Generic PETG"]
    cfg.resize_vectors(1, ["temperature"])
    assert cfg.vector("temperature") == ["220"]
    cfg.set("spiral_vase", True)
    assert cfg.get("spiral_vase") == "1"


def test_parse_ini_sections_keeps_order_and_values():
    sections = parse_ini_sections("# c\nversion = 1\n[printer:A]\nx = 1 = 2\ninherits = *c*\n[vendor:V]\nmodel:M = 0.4;0.6\n")
    assert sections[""]["version"] == "1"
    assert sections["printer:A"] == {"x": "1 = 2", "inherits": "*c*"}
    assert sections["vendor:V"]["model:M"] == "0.4;0.6"


