def test_from_file_reads_ini_and_3mf(tmp_path):
    ini = tmp_path / "exported.ini"
    ini.write_text("# generated\nlayer_height = 0.3\nprinter_settings_id = X\n", encoding="utf-8")
    cfg = PrusaConfig.from_file(str(ini))
    assert cfg.get("layer_height") == "0.3"
    import zipfile

    p = tmp_path / "proj.3mf"
    with zipfile.ZipFile(p, "w") as z:
        z.writestr("Metadata/Slic3r_PE.config", "; layer_height = 0.15\n; nozzle_diameter = 0.4,0.4\n")
    cfg = PrusaConfig.from_file(str(p))
    assert cfg.vector("nozzle_diameter") == ["0.4", "0.4"]
    with zipfile.ZipFile(tmp_path / "empty.3mf", "w") as z:
        z.writestr("3D/3dmodel.model", "<model/>")
    with pytest.raises(ValueError):
        PrusaConfig.from_file(str(tmp_path / "empty.3mf"))
